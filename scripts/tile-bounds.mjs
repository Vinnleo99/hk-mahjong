// Measures each tile's raw artwork bounding box (in 60x80 viewBox units) by rendering it with resvg,
// and writes src/tileBounds.ts. tileSvg() uses these boxes to fit every drawing inside the safe area.
// Run: npx vite-node scripts/tile-bounds.mjs
import { Resvg } from '@resvg/resvg-js';
import { writeFileSync } from 'node:fs';
import { faceSvg } from '../src/tileSvg.ts';
export function bbox(svgInner, scale = 10) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 60 80" width="${60 * scale}" height="${80 * scale}">${svgInner}</svg>`;
  const img = new Resvg(svg, { font: { loadSystemFonts: false } }).render(); const { width: w, height: h } = img; const px = img.pixels;
  let x0 = w, y0 = h, x1 = -1, y1 = -1;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (px[(y * w + x) * 4 + 3] > 8) { if (x < x0) x0 = x; if (x > x1) x1 = x; if (y < y0) y0 = y; if (y > y1) y1 = y; }
  return [x0 / scale, y0 / scale, (x1 + 1) / scale, (y1 + 1) / scale].map(v => +v.toFixed(2));
}
if (process.env.GEN_BOUNDS) {
  const b = Array.from({ length: 42 }, (_, f) => bbox(faceSvg(f)));
  writeFileSync('src/tileBounds.ts', `// Generated by scripts/tile-bounds.mjs. Raw artwork boxes [x0,y0,x1,y1] in viewBox units.\nexport const ART_BOUNDS: [number, number, number, number][] = ${JSON.stringify(b)};\n`);
  console.log(b.map((v, i) => i + ':' + v.join(',')).join('\n'));
}
